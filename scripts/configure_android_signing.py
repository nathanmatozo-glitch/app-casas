#!/usr/bin/env python3
"""Configure the generated Flutter Android Gradle file for CI release signing."""
from pathlib import Path
import re
import sys


def replace_once(source: str, pattern: str, replacement, description: str) -> str:
    updated, count = re.subn(pattern, replacement, source, count=1, flags=re.MULTILINE)
    if count != 1:
        raise SystemExit(f"Could not safely configure Android signing: expected one {description}.")
    return updated


def configure_kotlin(path: Path) -> None:
    source = path.read_text(encoding="utf-8")
    if "releaseSigningConfigured" in source:
        return

    variables = """val signingStoreFile = file("app-casas-release.jks")
val signingStorePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
val signingKeyAlias = System.getenv("ANDROID_KEY_ALIAS")
val signingKeyPassword = System.getenv("ANDROID_KEY_PASSWORD")
val releaseSigningConfigured =
    signingStoreFile.isFile &&
        !signingStorePassword.isNullOrBlank() &&
        !signingKeyAlias.isNullOrBlank() &&
        !signingKeyPassword.isNullOrBlank()

"""
    source = replace_once(
        source,
        r"^android[ \t]*\{[ \t]*$",
        lambda match: variables + "android {",
        "android block",
    )

    def signing_configs(match: re.Match[str]) -> str:
        indent = match.group(1)
        return (
            f'{indent}signingConfigs {{\n'
            f'{indent}    if (releaseSigningConfigured) {{\n'
            f'{indent}        create("release") {{\n'
            f'{indent}            keyAlias = signingKeyAlias!!\n'
            f'{indent}            keyPassword = signingKeyPassword!!\n'
            f'{indent}            storeFile = signingStoreFile\n'
            f'{indent}            storePassword = signingStorePassword!!\n'
            f'{indent}        }}\n'
            f'{indent}    }}\n'
            f'{indent}}}\n\n'
            f'{indent}buildTypes {{'
        )

    source = replace_once(
        source,
        r"^([ \t]*)buildTypes[ \t]*\{[ \t]*$",
        signing_configs,
        "buildTypes block",
    )
    source = replace_once(
        source,
        r'^(?P<indent>[ \t]*)signingConfig[ \t]*=[ \t]*signingConfigs\.(?:getByName\(["\']debug["\']\)|debug)[ \t]*$',
        (
            r'\g<indent>signingConfig = if (releaseSigningConfigured) {'
            "\n"
            r'\g<indent>    signingConfigs.getByName("release")'
            "\n"
            r'\g<indent>} else {'
            "\n"
            r'\g<indent>    signingConfigs.getByName("debug")'
            "\n"
            r'\g<indent>}'
        ),
        "default debug signing line",
    )
    path.write_text(source, encoding="utf-8")


def configure_groovy(path: Path) -> None:
    source = path.read_text(encoding="utf-8")
    if "releaseSigningConfigured" in source:
        return

    variables = """def signingStoreFile = file('app-casas-release.jks')
def signingStorePassword = System.getenv('ANDROID_KEYSTORE_PASSWORD')
def signingKeyAlias = System.getenv('ANDROID_KEY_ALIAS')
def signingKeyPassword = System.getenv('ANDROID_KEY_PASSWORD')
def releaseSigningConfigured = signingStoreFile.isFile() &&
    signingStorePassword && signingKeyAlias && signingKeyPassword

"""
    source = replace_once(
        source,
        r"^android[ \t]*\{[ \t]*$",
        lambda match: variables + "android {",
        "android block",
    )

    def signing_configs(match: re.Match[str]) -> str:
        indent = match.group(1)
        return (
            f"{indent}signingConfigs {{\n"
            f"{indent}    if (releaseSigningConfigured) {{\n"
            f'{indent}        create("release") {{\n'
            f"            keyAlias signingKeyAlias\n"
            f"            keyPassword signingKeyPassword\n"
            f"            storeFile signingStoreFile\n"
            f"            storePassword signingStorePassword\n"
            f"{indent}        }}\n"
            f"{indent}    }}\n"
            f"{indent}}}\n\n"
            f"{indent}buildTypes {{"
        )

    source = replace_once(
        source,
        r"^([ \t]*)buildTypes[ \t]*\{[ \t]*$",
        signing_configs,
        "buildTypes block",
    )
    source = replace_once(
        source,
        r"^([ \t]*)signingConfig[ \t]*=?[ \t]*signingConfigs(?:\.getByName\([\"']debug[\"']\)|\.debug)[ \t]*$",
        r"\1signingConfig releaseSigningConfigured ? signingConfigs.release : signingConfigs.debug",
        "default debug signing line",
    )
    path.write_text(source, encoding="utf-8")


def main() -> None:
    kotlin = Path("android/app/build.gradle.kts")
    groovy = Path("android/app/build.gradle")
    if kotlin.is_file():
        configure_kotlin(kotlin)
    elif groovy.is_file():
        configure_groovy(groovy)
    else:
        sys.exit("Android Gradle file was not generated by Flutter.")


if __name__ == "__main__":
    main()
